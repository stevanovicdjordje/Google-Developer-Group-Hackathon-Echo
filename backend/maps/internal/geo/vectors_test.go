// Shared georeferencing test vectors, checked by this test and by the Dart
// client (mobile/maps/test/location/georef_vectors_test.dart). Regenerate with
//
//	go test ./internal/geo -run TestSharedVectors -update
var update = flag.Bool("update", false, "rewrite contracts/maps/testdata/georef.json")

const vectorsPath = "../../../../contracts/maps/testdata/georef.json"

type vectorProbe struct {
	Px     Point  `json:"px"`
	LatLng LatLng `json:"latLng"`
}

type vectorCase struct {
	Name          string          `json:"name"`
	Width         int             `json:"width"`
	Height        int             `json:"height"`
	ControlPoints [3]ControlPoint `json:"controlPoints"`
	Degenerate    bool            `json:"degenerate"`
	// The rest is absent for degenerate cases.
	MetersPerPixel float64       `json:"metersPerPixel,omitempty"`
	Quality        *Quality      `json:"quality,omitempty"`
	Probes         []vectorProbe `json:"probes,omitempty"`
}

type vectorFile struct {
	Comment   string       `json:"comment"`
	Tolerance struct {
		Pixels  float64 `json:"pixels"`
		Degrees float64 `json:"degrees"`
		Ratio   float64 `json:"ratio"`
	} `json:"tolerance"`
	Cases []vectorCase `json:"cases"`
}

// similarity builds control points for a plan at mpp m/px rotated by rot
// degrees (clockwise from north for the image's up direction) around origin.
func similarity(origin LatLng, mpp, rot float64, pts [3]Point) [3]ControlPoint {
	r := rot * math.Pi / 180
	cosLat := math.Cos(origin.Lat * math.Pi / 180)
	var cps [3]ControlPoint
	for i, p := range pts {
		e := mpp * (p.X*math.Cos(r) + p.Y*math.Sin(r))
		n := mpp * (p.X*math.Sin(r) - p.Y*math.Cos(r))
		cps[i] = ControlPoint{Px: p, LatLng: LatLng{
			Lat: origin.Lat + n/earthRadius*180/math.Pi,
			Lng: origin.Lng + e/(earthRadius*cosLat)*180/math.Pi,
		}}
	}
	return cps
}

func generateVectors() vectorFile {
	var f vectorFile
	f.Comment = "Georeferencing (3 control points, affine) test vectors shared by backend/maps (Go) and mobile/maps (Dart). " +
		"Generated by `go test ./internal/geo -run TestSharedVectors -update` in backend/maps; do not edit by hand."
	f.Tolerance.Pixels = 1e-6
	f.Tolerance.Degrees = 1e-9
	f.Tolerance.Ratio = 1e-9

	type spec struct {
		name   string
		w, h   int
		cps    [3]ControlPoint
		probes []Point
	}
	probes := func(w, h int) []Point {
		fw, fh := float64(w), float64(h)
		return []Point{{0, 0}, {fw, 0}, {0, fh}, {fw, fh}, {fw / 2, fh / 2}, {123.4, 56.7}}
	}
	seed := func() [3]ControlPoint {
		// Same construction as backend/maps/cmd/seed (north-up, 0.05 m/px).
		const lat0, lng0, mpp = 44.8000, 20.4000, 0.05
		cp := func(x, y float64) ControlPoint {
			return ControlPoint{Px: Point{x, y}, LatLng: LatLng{lat0 - y*mpp/111320.0, lng0 + x*mpp/(111320.0*0.7096)}}
		}
		return [3]ControlPoint{cp(0, 0), cp(1200, 0), cp(0, 800)}
	}
	skewed := similarity(LatLng{44.8125, 20.4612}, 0.05, 30, [3]Point{{50, 40}, {950, 80}, {500, 560}})
	skewed[2].Px.Y -= 120 // a misplaced control point

	specs := []spec{
		{"seed demo floor (north-up, 0.05 m/px, Belgrade)", 1200, 800, seed(), probes(1200, 800)},
		{"rotated 30°, Belgrade", 1000, 600, similarity(LatLng{44.8125, 20.4612}, 0.05, 30, [3]Point{{50, 40}, {950, 80}, {500, 560}}), probes(1000, 600)},
		{"rotated -135°, 0.1 m/px, southern hemisphere", 2000, 1500, similarity(LatLng{-33.8688, 151.2093}, 0.1, -135, [3]Point{{100, 100}, {1900, 200}, {900, 1400}}), probes(2000, 1500)},
		{"mirrored plan (y up), 0.02 m/px, Novi Sad", 800, 800, similarity(LatLng{45.2671, 19.8335}, 0.02, 0, [3]Point{{0, 800}, {800, 800}, {0, 0}}), probes(800, 800)},
		{"misplaced control point (large error estimate)", 1000, 600, skewed, probes(1000, 600)},
	}
	for _, s := range specs {
		g, err := NewGeoref(s.cps)
		if err != nil {
			panic(s.name + ": " + err.Error())
		}
		q := g.Quality(s.w, s.h)
		c := vectorCase{Name: s.name, Width: s.w, Height: s.h, ControlPoints: s.cps, MetersPerPixel: g.MetersPerPixel(), Quality: &q}
		for _, p := range s.probes {
			c.Probes = append(c.Probes, vectorProbe{Px: p, LatLng: g.ToLatLng(p)})
		}
		f.Cases = append(f.Cases, c)
	}
	f.Cases = append(f.Cases, vectorCase{
		Name: "collinear (degenerate)", Width: 1000, Height: 600, Degenerate: true,
		ControlPoints: [3]ControlPoint{
			{Px: Point{0, 0}, LatLng: LatLng{44.81, 20.46}},
			{Px: Point{100, 0}, LatLng: LatLng{44.81, 20.461}},
			{Px: Point{200, 0}, LatLng: LatLng{44.81, 20.462}},
		},
	})
	return f
}

func TestSharedVectors(t *testing.T) {
	if *update {
		b, err := json.MarshalIndent(generateVectors(), "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll("../../../../contracts/maps/testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsPath, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	b, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("%v (run with -update to create it)", err)
	}
	var f vectorFile
	if err := json.Unmarshal(b, &f); err != nil {
		t.Fatal(err)
	}
	if len(f.Cases) < 5 {
		t.Fatalf("only %d cases", len(f.Cases))
	}
	near := func(a, b, tol float64) bool { return math.Abs(a-b) <= tol*math.Max(1, math.Abs(b)) }
	for _, c := range f.Cases {
		g, err := NewGeoref(c.ControlPoints)
		if c.Degenerate {
			if !errors.Is(err, ErrDegenerate) {
				t.Errorf("%s: want ErrDegenerate, got %v", c.Name, err)
			}
			continue
		}
		if err != nil {
			t.Errorf("%s: %v", c.Name, err)
			continue
		}
		if !near(g.MetersPerPixel(), c.MetersPerPixel, f.Tolerance.Ratio) {
			t.Errorf("%s: metersPerPixel %v, want %v", c.Name, g.MetersPerPixel(), c.MetersPerPixel)
		}
		q := g.Quality(c.Width, c.Height)
		if !near(q.EstimatedErrorMeters, c.Quality.EstimatedErrorMeters, 1e-6) ||
			!near(q.SkewDegrees, c.Quality.SkewDegrees, 1e-6) ||
			!near(q.ScaleMismatchPercent, c.Quality.ScaleMismatchPercent, 1e-6) {
			t.Errorf("%s: quality %+v, want %+v", c.Name, q, *c.Quality)
		}
		for _, p := range c.Probes {
			ll := g.ToLatLng(p.Px)
			if math.Abs(ll.Lat-p.LatLng.Lat) > f.Tolerance.Degrees || math.Abs(ll.Lng-p.LatLng.Lng) > f.Tolerance.Degrees {
				t.Errorf("%s: ToLatLng(%v) = %v, want %v", c.Name, p.Px, ll, p.LatLng)
			}
			if d := Dist(g.ToPixel(p.LatLng), p.Px); d > f.Tolerance.Pixels {
				t.Errorf("%s: ToPixel(%v) off by %g px", c.Name, p.LatLng, d)
			}
		}
	}
}
